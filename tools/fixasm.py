#!/usr/bin/env python3
"""Post-process splat's assembly so that the EE GNU assembler 2.10 reproduces the original words.

Rules found in Phase 0 and during the identical rebuild (applied to the `.text` file; each line carries the
original word in its comment, which is what the checks use):
  * a backward branch of five words or fewer is emitted as a raw `.word` (the assembler would insert NOPs);
  * the VU0 special registers $ACC, $Q, $I, $R, $P are written bare;
  * `.set nomacro` is added after `.set noreorder`, so any macro expansion is an error instead of silently
    changing the layout;
  * extra labels are inserted at code addresses that other code refers to, which splat cannot name by itself
    (config/extra_labels.txt, generated by tools/link_support.py).
  * the file is cut into chunks of about --chunk lines at function boundaries (the assembler is quadratic in
    file size; the linker puts the chunks back in order).
Usage: fixasm.py IN.s OUTDIR [--labels FILE] [--chunk N]    writes OUTDIR/text.NNN.s
"""
import argparse, re, sys
from pathlib import Path

SPECIAL = re.compile(r'\$(ACC|Q|I|R|P)\b')  # VU0 macro-mode registers are bare names for this assembler
INSTR = re.compile(r'^(\s+)/\* ([0-9A-F]+) ([0-9A-F]{8}) ([0-9A-F]{8}) \*/(\s+)(.*)$')
BRANCH_OPS = {0x04, 0x05, 0x06, 0x07, 0x14, 0x15, 0x16, 0x17}
REGIMM_RT = {0x00, 0x01, 0x02, 0x03, 0x10, 0x11, 0x12, 0x13}


def branch_offset(word):
    """Signed word offset of a conditional branch (relative to the delay slot), or None."""
    op = word >> 26
    if op in BRANCH_OPS or (op == 1 and ((word >> 16) & 31) in REGIMM_RT) or \
            (op in (0x10, 0x11, 0x12) and (word >> 21) & 31 == 8):
        off = word & 0xFFFF
        return off - 0x10000 if off & 0x8000 else off
    return None


def process(lines, labels, short=5):
    out, raw, nomacro = [], 0, False
    for line in lines:
        if not nomacro and line.strip() == '.set noreorder':
            out.append(line)
            out.append('.set nomacro')
            nomacro = True
            continue
        m = INSTR.match(line)
        if m:
            vram = int(m.group(3), 16)
            b = bytes.fromhex(m.group(4))
            word = int.from_bytes(b, 'little')
            for name in labels.get(vram, ()):
                out.append('glabel %s' % name)
            off = branch_offset(word)
            if off is not None and -short <= off < 0 and not m.group(6).startswith('.word'):
                line = '%s/* %s %s %s */%s.word 0x%08X' % (m.group(1), m.group(2), m.group(3), m.group(4), m.group(5), word)
                raw += 1
            elif '$ACC' in line or '$Q' in line or '$I' in line or '$R' in line or '$P' in line:
                line = '%s/* %s %s %s */%s%s' % (m.group(1), m.group(2), m.group(3), m.group(4), m.group(5),
                                                 SPECIAL.sub(r'\1', m.group(6)))
        out.append(line)
    return out, raw


HEADER = ['.include "macro.inc"', '', '.set noat', '.set noreorder', '.set nomacro', '', '.section .text, "ax"', '']


def chunks(lines, size):
    """Cut at `.align 3` lines that start a function, once the current chunk holds `size` lines."""
    out, cur = [], []
    for i, line in enumerate(lines):
        if len(cur) >= size and line == '.align 3' and i + 1 < len(lines) and lines[i + 1].startswith('glabel '):
            k = len(cur)  # the function's `.extern` block (gp-relative symbols) goes with it
            while k and (cur[k - 1] == '' or cur[k - 1].startswith(('.extern', '/* Symbols accessed'))):
                k -= 1
            out.append(cur[:k])
            cur = list(HEADER) + cur[k:]
        cur.append(line)
    out.append(cur)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('src')
    ap.add_argument('dst')
    ap.add_argument('--chunk', type=int, default=20000)
    ap.add_argument('--labels')
    a = ap.parse_args()
    labels = {}
    if a.labels and Path(a.labels).exists():
        for l in Path(a.labels).read_text().split('\n'):
            if l.strip():
                name, addr = l.split()
                labels.setdefault(int(addr, 16), []).append(name)
    out, raw = process(Path(a.src).read_text().split('\n'), labels)
    dst = Path(a.dst)
    dst.mkdir(parents=True, exist_ok=True)
    for old in dst.glob('text.*.s'):
        old.unlink()
    parts = chunks(out, a.chunk)
    for i, part in enumerate(parts):
        (dst / ('text.%03d.s' % i)).write_text('\n'.join(part) + '\n')
    print('%s: %d chunks, %d short backward branches emitted as .word, %d extra labels' % (
        a.dst, len(parts), raw, sum(map(len, labels.values()))))


if __name__ == '__main__':
    main()
