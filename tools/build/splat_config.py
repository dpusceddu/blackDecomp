#!/usr/bin/env python3
"""Generate the splat64 configuration for a retail boot executable from its ELF section table.

Usage: splat_config.py GAME_ID [--elf PATH]      (default ELF: orig/GAME_ID/GAME_ID)
Writes config/<GAME_ID>/splat.yaml (committed: addresses, offsets and options only) and the headerless "rom"
splat reads, build/<GAME_ID>/rom.bin (ignored; the loaded segment bytes taken from the ELF file). Each ELF
section becomes one subsegment: .text as assembly, .data/.rodata/.lit4/.sdata/.gcc_except_table as data,
.sbss/.bss as no-load, .vutext/.vudata as binary blobs. Non-loaded sections (.reginfo, the DVP overlays,
.debug_str, .shstrtab) are handled by tools/build/pack_elf.py, not by splat.
"""
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(ROOT / 'tools' / d) for d in ('', 'build', 'pipeline', 'maint')]
from elfinfo import Elf

MAP = {'.text': 'asm', '.vutext': 'textbin', '.data': 'data', '.vudata': 'databin', '.rodata': 'rodata',
       '.gcc_except_table': 'gcc_except_table', '.lit4': 'lit4', '.lit8': 'lit8', '.sdata': 'sdata',
       '.sbss': 'sbss', '.bss': 'bss', '.vubss': 'bss'}


def sections(elf):
    """Loaded sections in address order: name, type, addr, file offset, size, nobits."""
    out = []
    for s in sorted(elf.sections, key=lambda s: (s['addr'], s['index'])):
        if s['index'] and s['flags'] & 2 and s['name'] in MAP and s['size']:
            out.append(s)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('slug')
    ap.add_argument('--elf')
    a = ap.parse_args()
    variants = json.loads((ROOT / 'config/versions.json').read_text())
    boot = variants[a.slug]['boot']
    path = Path(a.elf) if a.elf else ROOT / 'orig' / a.slug / boot
    data = path.read_bytes()
    elf = Elf(data)
    secs = sections(elf)
    first = next(s for s in secs if s['type'] != 8)
    base = first['offset']
    last_file = max((s for s in secs if s['type'] != 8), key=lambda s: s['offset'])
    rom = data[base:last_file['offset'] + last_file['size']]
    (ROOT / 'build' / a.slug).mkdir(parents=True, exist_ok=True)
    (ROOT / 'build' / a.slug / 'rom.bin').write_bytes(rom)
    gp = Elf(data).content(elf.section('.reginfo'))[20:24]
    gp = int.from_bytes(gp, 'little')
    names = [s['name'] for s in secs]
    bss = [s for s in secs if s['type'] == 8]
    out = ['# splat64 configuration for %s (%s); generated by tools/build/splat_config.py' % (boot, a.slug), 'options:',
           '  basename: %s' % boot, '  target_path: build/%s/rom.bin' % a.slug,
           '  elf_path: build/%s/%s.elf' % (a.slug, boot), '  base_path: ../..', '  platform: ps2',
           '  compiler: EEGCC', '  gp_value: 0x%08X' % gp,
           '  ld_gp_expression: main_LIT4_START + 0x7FF0', '',
           '  asm_path: asm/%s' % a.slug, '  data_path: data', '  asset_path: data/%s' % a.slug,
           '  generate_asm_macros_files: False', '  asm_nonmatching_label_macro: ""',
           '  src_path: src', '  build_path: build/%s' % a.slug, '',
           '  ld_script_path: build/%s/%s.ld' % (a.slug, boot), '  ld_dependencies: False',
           '  ld_wildcard_sections: False', '  ld_bss_contains_common: False',
           '  create_asm_dependencies: False', '  find_file_boundaries: False',
           '  o_as_suffix: True', '  use_gp_rel_macro: False', '  use_gp_rel_macro_nonmatching: False',
           '  symbol_addrs_path: config/%s/boundaries.txt' % boot,
           '  undefined_funcs_auto_path: build/%s/undefined_funcs_auto.txt' % a.slug,
           '  undefined_syms_auto_path: build/%s/undefined_syms_auto.txt' % a.slug,
           '  string_encoding: ASCII', '  data_string_encoding: ASCII',
           '  rodata_string_guesser_level: 2', '  data_string_guesser_level: 2',
           '  named_regs_for_c_funcs: False', '  mips_abi_gpr: numeric', '  mips_abi_float_regs: numeric', '', '  section_order: [%s]' % ', '.join('".%s"' % n.lstrip('.') for n in names if n not in ('.vutext', '.vudata', '.vubss')),
           '', 'sha1: %s' % __import__('hashlib').sha1(rom).hexdigest(), '',
           'segments:', '  - name: main', '    type: code', '    start: 0x0', '    vram: 0x%08X' % first['addr'],
           '    bss_size: 0x%X' % (bss[-1]['addr'] + bss[-1]['size'] - bss[0]['addr']),
           '    subalign: null', '    subsegments:']
    for i, s in enumerate(secs):
        t = MAP[s['name']]
        nm = s['name'].lstrip('.')
        if s['type'] == 8:
            out.append('      - { type: %s, vram: 0x%08X, name: %s } # %s size 0x%X' % (t, s['addr'], nm, s['name'], s['size']))
        else:
            out.append('      - [0x%06X, %s, %s] # %s addr 0x%08X size 0x%X' % (s['offset'] - base, t, nm, s['name'], s['addr'], s['size']))
        # alignment gaps between sections end the section: otherwise splat would swallow them into it
        nxt = secs[i + 1] if i + 1 < len(secs) else None
        end = s['addr'] + s['size']
        if nxt and nxt['addr'] > end:
            if s['type'] == 8:
                out.append('      - { type: bss, vram: 0x%08X, name: %s_gap } # alignment gap, not linked' % (end, nm))
            else:
                out.append('      - [0x%06X, pad, %s_gap] # alignment gap, not linked' % (end - first['addr'], nm))
    out.append('  - [0x%X]' % len(rom))
    cfg = ROOT / 'config' / boot / 'splat.yaml'
    cfg.write_text('\n'.join(out) + '\n')
    print('wrote', cfg.relative_to(ROOT), 'and build/%s/rom.bin' % a.slug, '(%d bytes)' % len(rom))


if __name__ == '__main__':
    main()
