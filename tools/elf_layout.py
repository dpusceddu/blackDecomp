#!/usr/bin/env python3
"""Describe the container of a retail boot ELF (headers and non-loaded sections) for tools/pack_elf.py.

Usage: elf_layout.py VARIANT_SLUG
Writes config/<boot file>.layout.json (committed: ELF header fields, program header, and one record per section
with name, type, flags, address, alignment, entry size, link and info; no game bytes) and extracts the opaque
payload of the non-loaded sections (the DVP overlay images and their string table, .DVP.ovlytab) into
data/<slug>/elf/NNN.bin (ignored), the same way splat extracts .vutext. `.reginfo` is stored as its fields,
`.shstrtab` and the one-byte `.debug_str` are regenerated by the packer.
"""
import sys as _sys
if __name__ == '__main__' and _sys.argv[1:2] in (['-h'], ['--help']):
    print(__doc__.strip())
    raise SystemExit(0)
import json, struct, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from elfinfo import Elf


def main():
    slug = sys.argv[1]
    boot = json.loads((ROOT / 'config/variants.json').read_text())[slug]['boot']
    data = (ROOT / 'orig' / slug / 'files' / boot).read_bytes()
    e = Elf(data)
    out = ROOT / 'data' / slug / 'elf'
    out.mkdir(parents=True, exist_ok=True)
    ph = e.segments[0]
    layout = dict(
        header=dict(type=e.type, machine=e.machine, entry=e.entry, flags=e.flags, phoff=e.phoff,
                    phentsize=e.phentsize, phnum=e.phnum, shentsize=e.shentsize, ident=data[:16].hex()),
        segment=dict(type=ph['type'], offset=ph['offset'], vaddr=ph['vaddr'], flags=ph['flags'], align=ph['align']),
        sections=[])
    for s in e.sections[1:]:
        rec = dict(name=s['name'], type=s['type'], flags=s['flags'], addr=s['addr'], align=s['align'],
                   entsize=s['entsize'], link=s['link'], info=s['info'])
        n = s['name']
        if n == '.reginfo':
            rec['source'] = 'reginfo'
            rec['reginfo'] = dict(gprmask=struct.unpack_from('<I', e.content(s), 0)[0],
                                  cprmask=list(struct.unpack_from('<4I', e.content(s), 4)))
        elif n == '.shstrtab':
            rec['source'] = 'shstrtab'
        elif n == '.debug_str':
            rec['source'] = 'zero'
            rec['size'] = s['size']
        elif s['flags'] & 2 or s['type'] == 8:
            rec['source'] = 'linked'
            rec['orig_size'] = s['size']  # informational: the retail size (the linker output decides)
        else:
            rec['source'] = 'blob'
            rec['blob'] = 'elf/%03d.bin' % s['index']
            rec['size'] = s['size']
            (out / ('%03d.bin' % s['index'])).write_bytes(e.content(s))
        layout['sections'].append(rec)
    # .DVP.ovlytab holds (id, address inside .vutext, offset) triples; the packer rebases the addresses
    vt = e.section('.vutext')
    tab = next(r for r in layout['sections'] if r['name'] == '.DVP.ovlytab')
    tab['rebase'] = dict(stride=12, field=4, base_section='.vutext', base_addr=vt['addr'], size=vt['size'])
    # gp: the linker defines _gp relative to the first small-data section
    rg = e.content(e.section('.reginfo'))
    gp = struct.unpack_from('<I', rg, 20)[0]
    small = next(r for r in layout['sections'] if r['name'] in ('.lit4', '.lit8', '.sdata', '.sbss'))
    layout['gp'] = dict(section=small['name'], offset=gp - small['addr'])
    layout['entry_symbol'] = 'func_%08X' % e.entry
    p = ROOT / 'config' / ('%s.layout.json' % boot)
    p.write_text(json.dumps(layout, indent=1) + '\n')
    print('wrote', p.relative_to(ROOT), '%d sections' % len(layout['sections']), '; blobs in data/%s/elf' % slug)


if __name__ == '__main__':
    main()
