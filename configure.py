#!/usr/bin/env python3
"""Generate the standard Ninja build for one retail version or the NON_MATCHING drafts."""
import argparse
import json
from pathlib import Path
import sys
import subprocess

ROOT = Path(__file__).resolve().parent


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--version', default='SLUS_213.76')
    ap.add_argument('--non-matching', action='store_true')
    a = ap.parse_args()
    versions = json.loads((ROOT / 'config/versions.json').read_text())
    if a.version not in versions:
        ap.error('unknown version')
    slug = a.version
    boot = versions[slug]['boot']
    b = 'build/' + slug
    out = b + ('-nm' if a.non_matching else '')
    nm = ' --non-matching' if a.non_matching else ''
    py = '.venv/bin/python' if (ROOT / '.venv/bin/python').exists() else 'python3'
    config = ['config/%s/%s' % (slug,n) for n in ('splits.yaml','symbols.txt') if (ROOT / 'config' / slug / n).exists()]
    explicit = 'config/%s/explicit_boundaries.txt' % slug
    if not (ROOT / explicit).exists():
        explicit = ''
    text = f'''# Generated by configure.py; do not edit.
ninja_required_version = 1.10
py = {py}
rule needexe
  command = $py tools/build/preflight.py exe {slug}
  generator = 1
rule extract
  command = $py tools/build/preflight.py exe {slug} && $py tools/build/splat_config.py {slug} && $py tools/build/elf_layout.py {slug} && touch $out
rule boundaries
  command = $py tools/build/boundaries.py {slug}
rule split
  command = rm -rf asm/{slug} && $py -m splat split {b}/splat.yaml > {b}/splat.log 2>&1 && touch $out
  description = SPLAT {slug}
rule support
  command = $py tools/build/link_support.py {slug}
rule placement
  command = $py tools/build/split_objects.py {slug} --functions && $py tools/build/split_objects.py {slug}
  description = generate function includes and data ownership
rule graph
  command = $py tools/build/object_graph.py {slug}{nm}
  generator = 1
  restat = 1
rule object
  command = $py tools/build/object_compile.py $spec $out
  depfile = $out.d
  deps = gcc
  description = OBJECT $in
rule objdiff_unit
  command = $py tools/objdiff.py --unit $spec --output $base
  description = OBJDIFF $in
rule unit_link
  command = $py tools/build/unit_link.py {slug}{nm}
  description = LINK {out}/linked.elf
  pool = console
rule pack
  command = $py tools/build/pack_elf.py {out}/linked.elf {b}/layout.json data/{slug}/elf {out}/{boot}.elf
  description = PACK {boot}
rule check
  command = $py tools/check_elf.py {slug} {out}/{boot}.elf --stamp $out
  description = CHECK {boot}
  pool = console
rule progress
  command = $py tools/progress.py {slug}
  pool = console
rule objdiff
  command = $py tools/objdiff.py {slug}
  pool = console
rule report
  command = $py tools/objdiff.py {slug} --report
  pool = console
rule badges
  command = $py tools/badges.py {slug}
  pool = console
rule owners
  command = $py tools/build/linkonce_owners.py --write
rule tus
  command = $py tools/build/tus.py map --out $out
rule classes
  command = $py tools/autodecomp.py context --refresh && $py tools/maint/class_skeletons.py
  pool = console
build orig/{slug}/{boot}: needexe
build {b}/extract.stamp: extract orig/{slug}/{boot} | tools/build/splat_config.py tools/build/elf_layout.py
build {b}/boundaries.txt: boundaries orig/{slug}/{boot} | tools/build/boundaries.py {explicit}
build {b}/split.stamp: split {b}/extract.stamp {b}/boundaries.txt
build {b}/extra_labels.txt {b}/symbols.ld: support {b}/split.stamp | tools/build/link_support.py
build {b}/placement.json: placement {b}/extra_labels.txt | tools/build/split_objects.py tools/build/fixasm.py tools/build/source_data.py {' '.join(config)}
build {out}/objects.ninja: graph {b}/placement.json | tools/build/object_graph.py tools/build/asm_syntax.py {' '.join(config)}
subninja {out}/objects.ninja
build {out}/{boot}.elf: pack {out}/linked.elf | tools/build/pack_elf.py
build {out}/ok.stamp: check {out}/{boot}.elf | tools/check_elf.py config/{slug}/checksums.sha256
build all: phony {out + '/' + boot + '.elf' if a.non_matching else out + '/ok.stamp'}
default all
'''
    derived = ''
    if slug == 'SLUS_213.76':
        text += f'''build {b}/inline_owners.txt: owners {b}/split.stamp | config/{slug}/libraries.txt tools/build/linkonce_owners.py
build {b}/tus.yaml: tus {b}/placement.json | config/tus_overrides.yaml config/{slug}/libraries.txt tools/build/tus.py
build owners: phony {b}/inline_owners.txt
build tus: phony {b}/tus.yaml
build classes: classes | {b}/placement.json
'''
        derived = f'{b}/inline_owners.txt {b}/tus.yaml'
    text += f'''build progress: progress | {out}/linked.elf {derived}
build objdiff: objdiff | {out}/linked.elf {derived} tools/objdiff.py
build report: report | {out}/linked.elf {derived} tools/objdiff.py
build badges: badges | {out}/linked.elf {derived} tools/badges.py
'''
    bootstrap = ROOT / out / 'bootstrap.ninja'
    bootstrap.parent.mkdir(parents=True, exist_ok=True)
    bootstrap.write_text(text.replace('subninja '+out+'/objects.ninja', ''))
    if (ROOT / 'orig' / slug / boot).is_file():
        subprocess.run(['ninja', '-f', str(bootstrap.relative_to(ROOT)), out + '/objects.ninja'], cwd=ROOT, check=True)
    else:
        graph = ROOT / out / 'objects.ninja'
        if not graph.exists():
            graph.write_text('# Supply orig/<version>/<boot>, then run configure.py.\n')
    text += f"""rule reconfigure
  command = $py configure.py --version {slug}{nm}
  generator = 1
build build.ninja: reconfigure configure.py {' '.join(config)} tools/build/object_graph.py tools/build/asm_syntax.py
"""
    if not (ROOT / 'orig' / slug / boot).is_file():
        text=text.replace('default all','default orig/'+slug+'/'+boot)
    (ROOT / 'build.ninja').write_text(text)
    print('wrote build.ninja for ' + slug + (' (NON_MATCHING)' if a.non_matching else ''))


if __name__ == '__main__':
    main()
