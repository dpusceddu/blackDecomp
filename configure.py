#!/usr/bin/env python3
"""Write build.ninja for the identical rebuild of one boot executable.

Usage: python3 configure.py [--variant usa-retail]    then `ninja`
Stages (see README.md): extract -> split (splat) -> support symbols -> post-process (fixasm) -> link script ->
assemble+link in the build backend -> pack the ELF container -> check against config/checksums.sha256.
`ninja` ends with `OK` or a mismatch report.
"""
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--variant', default='usa-retail')
    a = ap.parse_args()
    slug = a.variant
    boot = json.loads((ROOT / 'config/variants.json').read_text())[slug]['boot']
    py = ROOT / '.venv/bin/python'
    py = str(py.relative_to(ROOT)) if py.exists() else sys.executable
    tools = lambda *n: ' '.join('tools/%s' % x for x in n)
    b = 'build/%s' % slug
    out = f"""# Generated by configure.py --variant {slug}; do not edit.
ninja_required_version = 1.10
py = {py}

rule extract
  command = $py tools/splat_config.py {slug} && $py tools/elf_layout.py {slug} && touch $out
  description = extract section layout and blobs from the target image
rule split
  command = rm -rf asm/{slug} && $py -m splat split config/{boot}.yaml > {b}/splat.log 2>&1 && touch $out
  description = splat split (disassemble and split)
rule support
  command = $py tools/link_support.py {slug}
  description = define symbols splat cannot (labels inside code, offsets into data)
rule objsplit
  command = $py tools/split_objects.py {slug}
  description = one assembly file per function; constants migrate to their only user
rule ldscript
  command = $py tools/make_ld.py {slug}
  description = write the linker script (original order, source units replace functions)
rule link
  command = $py tools/build_objects.py {slug}
  description = assemble and compile what changed, then link, in the build backend
  depfile = {b}/link.d
  pool = console
rule pack
  command = $py tools/pack_elf.py {b}/linked.elf config/{boot}.layout.json data/{slug}/elf {b}/{boot}.elf
  description = pack the ELF container
rule progress
  command = $py tools/progress.py {slug}
  description = share of .text provided by source
  pool = console
rule check
  command = $py tools/check_elf.py {slug} {b}/{boot}.elf --stamp $out
  description = compare with the target
  pool = console

build {b}/extract.stamp config/{boot}.yaml config/{boot}.layout.json: extract orig/{slug}/files/{boot} | {tools('splat_config.py', 'elf_layout.py', 'elfinfo.py')}
build {b}/split.stamp: split | {b}/extract.stamp config/boundaries.{slug}.txt
build {b}/extra_labels.txt {b}/symbols.ld: support | {b}/split.stamp tools/link_support.py
build {b}/placement.json: objsplit | {b}/extra_labels.txt tools/split_objects.py tools/fixasm.py
build {b}/link.ld {b}/objects.json: ldscript | {b}/placement.json {b}/symbols.ld tools/make_ld.py tools/units.py config/units.yaml config/{boot}.layout.json
build {b}/linked.elf: link | {b}/link.ld {b}/objects.json include/macro.inc {tools('build_objects.py', 'build_job.py', 'sandbox.py', 'elfobj.py', 'assembler.py', 'units.py')}
build {b}/{boot}.elf: pack | {b}/linked.elf tools/pack_elf.py
build {b}/ok.stamp: check | {b}/{boot}.elf tools/check_elf.py config/checksums.sha256
build progress: progress | {b}/linked.elf
build all: phony {b}/ok.stamp
default all
"""
    (ROOT / 'build.ninja').write_text(out)
    print('wrote build.ninja for %s (%s)' % (slug, boot))


if __name__ == '__main__':
    main()
