#!/usr/bin/env python3
"""Write build.ninja for the identical rebuild of one boot executable.

Usage: python3 configure.py [--version SLUS_213.76] [--non-matching]    then `ninja`
Stages (see docs/build.md): extract -> split (splat) -> support symbols -> function table -> units (split list + INCLUDE_ASM
markers) -> per-function assembly -> compile -> verify -> link script -> assemble+link with the build toolchain -> pack the ELF
container -> check against config/<GAME_ID>/checksums.sha256. `ninja` ends with `OK` or a mismatch report naming the functions.
--non-matching writes a build.ninja whose `ninja` builds the NON_MATCHING drafts into a separate executable
(build/<GAME_ID>-nm/<boot>.nonmatching.elf); it is not checked against the original.
"""
import argparse, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--non-matching', action='store_true', help='build the NON_MATCHING drafts into a separate ELF (not a match)')
    ap.add_argument('--version', default='SLUS_213.76', help='boot game ID: SLUS_213.76 (default), SLES_538.86, SLES_540.30, SLKA_253.72, SLPM_663.54')
    a = ap.parse_args()
    slug = a.version
    if slug not in json.loads((ROOT / 'config/versions.json').read_text()) or not (ROOT / 'config' / slug).is_dir():
        raise SystemExit('unknown version %s; see config/<GAME_ID>/' % slug)
    boot = json.loads((ROOT / 'config/versions.json').read_text())[slug]['boot']
    sys.path[:0] = [str(ROOT / 'tools' / d) for d in ('', 'build')]
    import backend, toolchain
    if backend.name() == 'local':        # a missing toolchain is reported here, not in the middle of the build
        for line in toolchain.problems():
            print('note: %s (python3 tools/toolchain.py install)' % line, file=sys.stderr)
    py = ROOT / '.venv/bin/python'
    py = str(py.relative_to(ROOT)) if py.exists() else sys.executable
    def tools(*names):       # paths of tools/ files by name, wherever they live (tools/, tools/build/, ...)
        return ' '.join(str(next(p for p in ((ROOT / 'tools' / d / n) for d in ('', 'build', 'pipeline', 'maint')) if p.exists()).relative_to(ROOT)) for n in names)
    if (ROOT / 'config' / slug / 'splits.yaml').exists():       # every function has one owner file, the ranges do not overlap
        import splits
        problems = splits.check(slug)
        if problems:
            raise SystemExit('config/%s/splits.yaml: %d problems, for example\n  %s' % (slug, len(problems), '\n  '.join(problems[:10])))
    b = 'build/%s' % slug
    have = [n for n in ('splits.yaml', 'symbols.txt') if (ROOT / 'config' / slug / n).exists()]
    inputs = ' '.join('config/%s/%s' % (slug, n) for n in have)
    sym = 'config/%s/symbols.txt' % slug if 'symbols.txt' in have else ''
    explicit = 'config/%s/explicit_boundaries.txt' % slug if (ROOT / 'config' / slug / 'explicit_boundaries.txt').exists() else ''
    usa = slug == 'SLUS_213.76'       # the libraries, link-once owners and TU map exist for the version with recovered source
    derived = '%s/inline_owners.txt %s/tus.yaml' % (b, b) if usa else ''
    derived_rules = f"""build {b}/inline_owners.txt: owners | {b}/split.stamp config/{slug}/libraries.txt {tools('linkonce_owners.py', 'layout.py')}
build {b}/tus.yaml: tus | {b}/units.json {b}/placement.json config/tus_overrides.yaml config/{slug}/libraries.txt {tools('tus.py')}
build run_classes: classes | {b}/units.json
build classes: phony run_classes
build owners: phony {b}/inline_owners.txt
build tus: phony {b}/tus.yaml
""" if usa else ''
    out = f"""# Generated by configure.py --version {slug}; do not edit.
ninja_required_version = 1.10
py = {py}

rule needexe
  command = $py tools/build/preflight.py exe {slug}
  description = the original executable orig/{slug}/{boot}
  generator = 1
rule extract
  command = $py tools/build/splat_config.py {slug} && $py tools/build/elf_layout.py {slug} && touch $out
  description = extract section layout and blobs from the target image
rule boundaries
  command = $py tools/build/boundaries.py {slug}
  description = function starts splat cannot see (build/{slug}/boundaries.txt)
rule split
  command = rm -rf asm/{slug} && $py -m splat split {b}/splat.yaml > {b}/splat.log 2>&1 && touch $out
  description = splat split (disassemble and split)
rule support
  command = $py tools/build/link_support.py {slug}
  description = define symbols splat cannot (labels inside code, offsets into data)
rule functions
  command = $py tools/build/split_objects.py {slug} --functions
  description = function table of the image
rule units
  command = $py tools/build/units.py {slug}
  depfile = {b}/units.d
  description = derive the source units (split list, INCLUDE_ASM markers, symbols)
rule objsplit
  command = $py tools/build/split_objects.py {slug}
  description = one assembly file per function (asm/{slug}/nonmatchings); constants migrate to their only user
rule compile
  command = $py tools/build/make_ld.py {slug} && $py tools/build/build_objects.py {slug} --compile-only && touch $out
  depfile = {b}/compile.d
  description = compile the source files
  pool = console
rule verify
  command = $py tools/build/units_verify.py prepare
  description = check that the compiled functions can take the place of the assembly
  restat = 1
  pool = console
rule ldscript
  command = $py tools/build/make_ld.py {slug}
  description = write the linker script (original order, source units replace functions)
rule nonmatching
  command = $py tools/build/nm_build.py {slug}
  description = build the NON_MATCHING drafts into build/{slug}-nm
  pool = console
rule link
  command = $py tools/build/build_objects.py {slug}
  description = assemble and compile what changed, then link, with the build toolchain
  depfile = {b}/link.d
  pool = console
rule pack
  command = $py tools/build/pack_elf.py {b}/linked.elf {b}/layout.json data/{slug}/elf {b}/{boot}.elf
  description = pack the ELF container
rule progress
  command = $py tools/progress.py {slug}
  description = share of .text provided by source
  pool = console
rule objdiff
  command = $py tools/objdiff.py {slug}
  description = write objdiff.json and the per-unit target and base objects
  pool = console
rule report
  command = $py tools/objdiff.py {slug} --report
  description = generate the objdiff progress report ({b}/report.json)
  pool = console
rule badges
  command = $py tools/badges.py {slug}
  description = write the progress badges and table (progress/, README.md)
  pool = console
rule classes
  command = $py tools/autodecomp.py context --refresh && $py tools/maint/class_skeletons.py
  description = class skeletons from RTTI and the vtables (build/classes/include)
  pool = console
rule owners
  command = $py tools/build/linkonce_owners.py --write
  description = owner library of every link-once copy (build/{slug}/inline_owners.txt)
rule tus
  command = $py tools/build/tus.py map --out $out
  description = translation unit map of the image (build/{slug}/tus.yaml)
  pool = console
rule check
  command = $py tools/check_elf.py {slug} {b}/{boot}.elf --stamp $out
  description = compare with the target
  pool = console

build orig/{slug}/{boot}: needexe
build {b}/extract.stamp {b}/splat.yaml {b}/layout.json: extract orig/{slug}/{boot} | {tools('splat_config.py', 'elf_layout.py', 'elfinfo.py')}
build {b}/boundaries.txt: boundaries | orig/{slug}/{boot} {tools('boundaries.py', 'elfinfo.py')} {explicit}
build {b}/split.stamp: split | {b}/extract.stamp {b}/boundaries.txt
build {b}/extra_labels.txt {b}/symbols.ld: support | {b}/split.stamp tools/build/link_support.py
build {b}/functions.json: functions | {b}/extra_labels.txt tools/build/split_objects.py
build {b}/units.json: units | {b}/functions.json {inputs} {tools('units.py', 'splits.py', 'include_asm.py')}
build {b}/placement.json: objsplit | {b}/units.json {b}/extra_labels.txt tools/build/split_objects.py tools/build/fixasm.py tools/build/source_data.py
build {b}/compiled.stamp: compile | {b}/placement.json {b}/units.json {b}/symbols.ld include/include_asm.h {tools('make_ld.py', 'build_objects.py', 'build_job.py', 'sandbox.py', 'assembler.py', 'source_data.py')}
build {b}/unit_facts.json: verify | {b}/compiled.stamp tools/build/units_verify.py {sym}
build {b}/link.ld {b}/objects.json: ldscript | {b}/unit_facts.json {b}/placement.json {b}/symbols.ld tools/build/make_ld.py tools/build/source_data.py {b}/layout.json
build {b}/linked.elf: link | {b}/link.ld {b}/objects.json include/macro.inc {tools('build_objects.py', 'build_job.py', 'sandbox.py', 'elfobj.py', 'assembler.py')}
build {b}/{boot}.elf: pack | {b}/linked.elf tools/build/pack_elf.py
build {b}/ok.stamp: check | {b}/{boot}.elf tools/check_elf.py config/{slug}/checksums.sha256
{derived_rules}build run_progress: progress | {b}/linked.elf {derived}
build progress: phony run_progress
build objdiff: objdiff | {b}/linked.elf {derived} {tools('objdiff.py', 'objdiff_job.py')}
build run_badges: badges | {b}/linked.elf {derived} {tools('badges.py', 'progress.py')}
build badges: phony run_badges
build report: report | {b}/linked.elf {derived} {tools('objdiff.py', 'objdiff_job.py')}
build nonmatching: nonmatching | {b}/placement.json {tools('nm_build.py')}
build all: phony {b}/ok.stamp
default {'nonmatching' if a.non_matching else 'all'}
"""
    (ROOT / 'build.ninja').write_text(out)
    print('wrote build.ninja for %s (%s)%s' % (slug, boot, ', NON_MATCHING build' if a.non_matching else ''))


if __name__ == '__main__':
    main()
